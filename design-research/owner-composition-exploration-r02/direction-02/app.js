function tr(key) {
	return COPY[lang][key] ?? key;
}
function fmt(key, values) {
	return tr(key).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}
function num(value) {
	return new Intl.NumberFormat(
		lang === "ar" ? "ar-SA-u-nu-latn" : "en-US",
	).format(value);
}
function decimal(value) {
	return new Intl.NumberFormat(lang === "ar" ? "ar-SA-u-nu-latn" : "en-US", {
		maximumFractionDigits: 1,
	}).format(value);
}
function clock(minute) {
	const hour = Math.floor(minute / 60);
	const m = minute % 60;
	const h = hour % 12 || 12;
	return `${num(h)}:${String(m).padStart(2, "0")} ${lang === "ar" ? (hour < 12 ? "ص" : "م") : hour < 12 ? "AM" : "PM"}`;
}
function interp(minute) {
	const right = anchors.findIndex(([t]) => t >= minute);
	if (right <= 0) return anchors[0][1];
	const [ta, va] = anchors[right - 1];
	const [tb, vb] = anchors[right];
	return va + ((vb - va) * (minute - ta)) / (tb - ta);
}
function band(count) {
	return count < 25
		? "quiet"
		: count < 50
			? "moderate"
			: count < 70
				? "busy"
				: "packed";
}
function createRecords(kind) {
	const rows = [];
	for (let minute = 6 * 60; minute < 22 * 60; minute++) {
		if (kind === "closed") {
			rows.push({ minute, state: "closed" });
			continue;
		}
		if (minute < 7 * 60 || minute >= 21 * 60) {
			rows.push({ minute, state: "closed" });
			continue;
		}
		if (
			kind === "no-readings" ||
			(minute >= 13 * 60 + 5 && minute <= 13 * 60 + 34)
		) {
			rows.push({ minute, state: "missing" });
			continue;
		}
		let count = Math.round(interp(minute) + Math.sin(minute * 0.093) * 1.15);
		count = Math.max(0, Math.min(72, count));
		if (minute === 18 * 60 + 20) count = 73;
		rows.push({ minute, state: "value", count, band: band(count) });
	}
	return rows;
}
