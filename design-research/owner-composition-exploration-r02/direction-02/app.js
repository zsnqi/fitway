function renderSnapshot() {
	const strip = document.querySelector(".state-strip");
	const reading = document.getElementById("state-reading");
	const meta = document.getElementById("state-meta");
	strip.className = `state-strip state-strip--${snapshotFixture}`;
	let disc = "status-disc";
	if (snapshotFixture === "stale") disc += " status-disc--amber";
	if (["closed", "unavailable", "loading"].includes(snapshotFixture))
		disc += " status-disc--muted";
	let label = "";
	let count = "";
	let sub = "";
	let time = "";
	if (snapshotFixture === "current") {
		label = tr("currentLabel");
		count = `${tr("moderate")} · ${fmt("snapshotCount", { n: num(37) })}`;
		time = fmt("updated", { time: clock(17 * 60 + 42) });
		sub = tr("stateFresh");
	} else if (snapshotFixture === "stale") {
		label = tr("staleLabel");
		count = `${tr("moderate")} · ${fmt("snapshotCount", { n: num(37) })}`;
		time = fmt("lastUpdated", { time: clock(16 * 60 + 31) });
		sub = tr("stateStale");
	} else if (snapshotFixture === "closed") {
		label = tr("closedSnapshot");
		time = tr("nextOpen");
	} else if (snapshotFixture === "unavailable") {
		label = tr("unavailableSnapshot");
		time = tr("unavailableNote");
	} else if (snapshotFixture === "loading") {
		label = tr("loadingSnapshot");
		time = tr("loadingNote");
	} else {
		label = tr("errorSnapshot");
		time = tr("errorNote");
	}
	reading.replaceChildren();
	const dot = document.createElement("span");
	dot.className = disc;
	dot.setAttribute("aria-hidden", "true");
	reading.append(dot);
	const strong = document.createElement("strong");
	strong.textContent = label;
	reading.append(strong);
	if (count) {
		const span = document.createElement("span");
		span.className = "state-count";
		span.textContent = count;
		reading.append(span);
	}
	meta.replaceChildren();
	if (sub) {
		const b = document.createElement("strong");
		b.textContent = sub;
		meta.append(b);
	}
	const m = document.createElement("span");
	m.textContent = time;
	meta.append(m);
	if (snapshotFixture === "error") {
		const button = document.createElement("button");
		button.className = "inline-retry";
		button.type = "button";
		button.textContent = tr("retry");
		button.setAttribute("aria-label", tr("snapshotRetry"));
		button.addEventListener("click", () => {
			snapshotFixture = "current";
			document.getElementById("snapshot-fixture").value = "current";
			writeQuery();
			renderSnapshot();
		});
		meta.append(button);
	}
}
function coord(minute) {
	const unmirrored = ((minute - 6 * 60) / (16 * 60)) * 1000;
	return lang === "ar" ? 1000 - unmirrored : unmirrored;
}
function yCoord(count) {
	return 270 - (count / 80) * 242;
}
function svgElement(name, attributes) {
	const el = document.createElementNS("http://www.w3.org/2000/svg", name);
	for (const [key, value] of Object.entries(attributes))
		el.setAttribute(key, String(value));
	return el;
}
function renderChart() {
	plotSvg.querySelectorAll("line,rect,path").forEach((node) => {
		node.remove();
	});
	for (const minute of [6 * 60, 10 * 60, 14 * 60, 18 * 60, 22 * 60])
		plotSvg.append(
			svgElement("line", {
				x1: coord(minute),
				x2: coord(minute),
				y1: 0,
				y2: 270,
				class: "tick-line",
			}),
		);
	for (const [start, end, type] of [
		[6 * 60, 7 * 60, "closed"],
		[13 * 60 + 5, 13 * 60 + 35, "missing"],
		[21 * 60, 22 * 60, "closed"],
	]) {
		const x1 = coord(start);
		const x2 = coord(end);
		plotSvg.append(
			svgElement("rect", {
				x: Math.min(x1, x2),
				y: 0,
				width: Math.abs(x2 - x1),
				height: 270,
				class: `${type}-wash`,
			}),
		);
	}
	plotSvg.append(
		svgElement("line", {
			x1: 0,
			y1: 270,
			x2: 1000,
			y2: 270,
			class: "baseline",
		}),
	);
	const runs = [];
	let run = [];
	for (const row of rows) {
		if (row.state === "value") {
			run.push(row);
		} else if (run.length) {
			runs.push(run);
			run = [];
		}
	}
	if (run.length) runs.push(run);
	for (const sequence of runs) {
		const sampled = sequence.filter(
			(r, i) =>
				i === 0 ||
				i === sequence.length - 1 ||
				i % 6 === 0 ||
				r.minute === 18 * 60 + 20,
		);
		const path = sampled
			.map(
				(r, i) =>
					`${i ? "L" : "M"}${coord(r.minute).toFixed(2)},${yCoord(r.count).toFixed(2)}`,
			)
			.join(" ");
		plotSvg.append(svgElement("path", { d: path, class: "under-path" }));
		plotSvg.append(svgElement("path", { d: path, class: "trajectory-path" }));
	}
	plotPoints.replaceChildren();
	for (const minute of [
		7 * 60 + 10,
		9 * 60 + 30,
		12 * 60 + 40,
		14 * 60 + 30,
		18 * 60 + 20,
		20 * 60 + 30,
	]) {
		const row = rows.find((r) => r.minute === minute);
		if (row?.state !== "value") continue;
		const button = document.createElement("button");
		button.className = "plot-point";
		button.type = "button";
		button.style.left = `${coord(minute) / 10}%`;
		button.style.top = `${(yCoord(row.count) / 290) * 100}%`;
		button.setAttribute(
			"aria-label",
			`${clock(minute)} · ${num(row.count)} · ${tr(row.band)}`,
		);
		button.setAttribute("aria-pressed", String(minute === selectedMinute));
		button.addEventListener("click", () => {
			selectedMinute = minute;
			renderChartSelection();
		});
		plotPoints.append(button);
	}
	document.getElementById("plot-times").replaceChildren(
		...[6 * 60, 10 * 60, 14 * 60, 18 * 60, 22 * 60].map((minute) => {
			const s = document.createElement("span");
			s.textContent = clock(minute);
			return s;
		}),
	);
	renderChartSelection();
}
function renderChartSelection() {
	plotPoints.querySelectorAll("button").forEach((button) => {
		const minute = [...plotPoints.children].indexOf(button);
		button.setAttribute(
			"aria-pressed",
			String(
				[
					7 * 60 + 10,
					9 * 60 + 30,
					12 * 60 + 40,
					14 * 60 + 30,
					18 * 60 + 20,
					20 * 60 + 30,
				][minute] === selectedMinute,
			),
		);
	});
	const row = rows.find(
		(r) => r.minute === selectedMinute && r.state === "value",
	);
	const dock = document.getElementById("detail-dock");
	if (!row) return;
	dock.className = "detail-dock";
	dock.replaceChildren();
	const time = document.createElement("strong");
	time.className = "detail-dock__time";
	time.textContent = clock(row.minute);
	const divider = document.createElement("i");
	divider.className = "detail-dock__divider";
	divider.setAttribute("aria-hidden", "true");
	const summary = document.createElement("span");
	summary.className = "detail-dock__summary";
	summary.textContent = `${fmt("people", { n: num(row.count) })} · ${tr(row.band)}`;
	const hint = document.createElement("span");
	hint.className = "detail-dock__hint";
	hint.textContent = tr("sourceNote");
	dock.append(time, divider, summary, hint);
}
function setStageState(kind) {
	const stage = document.getElementById("day-stage");
	stage.dataset.mode = "state";
	let titleKey = "";
	let textKey = "";
	let retry = false;
	if (kind === "closed") {
		titleKey = "closedDay";
		textKey = "closedDayText";
	}
	if (kind === "no-readings") {
		titleKey = "noReadings";
		textKey = "noReadingsText";
	}
	if (kind === "loading") {
		titleKey = "loadingDay";
		textKey = "loadingDayText";
	}
	if (kind === "error") {
		titleKey = "errorDay";
		textKey = "errorDayText";
		retry = true;
	}
	stage.querySelector(".state-stage")?.remove();
	const area = document.createElement("div");
	area.className = "state-stage";
	area.setAttribute("role", kind === "error" ? "alert" : "status");
	const heading = document.createElement("h2");
	heading.textContent = tr(titleKey);
	const detail = document.createElement("p");
	detail.textContent = tr(textKey);
	area.append(heading, detail);
	if (kind === "loading") {
		const sk = document.createElement("div");
		sk.className = "state-stage__skeleton";
		sk.setAttribute("aria-hidden", "true");
		area.prepend(sk);
	}
	if (retry) {
		const button = document.createElement("button");
		button.textContent = tr("retry");
		button.addEventListener("click", () => {
			dailyFixture = "populated";
			document.getElementById("daily-fixture").value = "populated";
			writeQuery();
			renderDaily();
		});
		area.append(button);
	}
	stage.append(area);
	document.getElementById("day-after").classList.add("day-after--hidden");
	document
		.getElementById("records")
		.classList.toggle(
			"records-section--hidden",
			kind === "loading" || kind === "error",
		);
	document.getElementById("more").classList.add("more-section--hidden");
}
function renderDaily() {
	rows = createRecords(
		dailyFixture === "closed"
			? "closed"
			: dailyFixture === "no-readings"
				? "no-readings"
				: "populated",
	);
	const stage = document.getElementById("day-stage");
	if (dailyFixture !== "populated") {
		setStageState(dailyFixture);
		if (dailyFixture === "closed") {
			document.getElementById("crossings-value").textContent = num(0);
		}
		renderTable();
		return;
	}
	stage.dataset.mode = "populated";
	stage.querySelector(".state-stage")?.remove();
	document.getElementById("day-after").classList.remove("day-after--hidden");
	document
		.getElementById("records")
		.classList.remove("records-section--hidden");
	document.getElementById("more").classList.remove("more-section--hidden");
	const values = rows.filter((r) => r.state === "value");
	const peak = values.reduce(
		(best, r) => (!best || r.count > best.count ? r : best),
		null,
	);
	const avg = values.reduce((sum, r) => sum + r.count, 0) / values.length;
	const expected = rows.filter((r) => r.state !== "closed").length;
	document.getElementById("peak-value").textContent = num(peak.count);
	document.getElementById("peak-time").textContent = clock(peak.minute);
	document.getElementById("average-value").textContent = decimal(avg);
	document.getElementById("coverage-value").textContent = fmt("coveredOf", {
		seen: num(values.length),
		expected: num(expected),
	});
	document.getElementById("crossings-value").textContent = num(286);
	renderChart();
	renderTable();
}
function renderTable() {
	const body = document.getElementById("record-rows");
	if (!body) return;
	const pages = Math.max(1, Math.ceil(rows.length / PAGE_SIZE));
	page = Math.max(0, Math.min(page, pages - 1));
	const start = page * PAGE_SIZE;
	const slice = rows.slice(start, start + PAGE_SIZE);
	body.replaceChildren();
	for (const row of slice) {
		const trEl = document.createElement("tr");
		const state =
			row.state === "value"
				? "recordedState"
				: row.state === "closed"
					? "closedState"
					: "missingState";
		const cells = [
			clock(row.minute),
			tr(state),
			row.state === "value" ? num(row.count) : "—",
			row.state === "value" ? tr(row.band) : "—",
		];
		for (const value of cells) {
			const td = document.createElement("td");
			td.textContent = value;
			trEl.append(td);
		}
		body.append(trEl);
	}
	document.getElementById("table-count").textContent = fmt("recordPage", {
		start: num(start + 1),
		end: num(start + slice.length),
		total: num(rows.length),
	});
	document.getElementById("page-number").textContent = fmt("page", {
		current: num(page + 1),
		total: num(pages),
	});
	document.getElementById("page-previous").disabled = page === 0;
	document.getElementById("page-next").disabled = page === pages - 1;
}
