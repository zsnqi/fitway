function normalizePath(value) {
	return value.replaceAll("\\", "/").replace(/^\.\//, "");
}

function pathExtension(file) {
	return path.posix.extname(file).toLowerCase();
}

function isTestFile(file) {
	return /\.(?:test|spec)\.[cm]?[jt]sx?$/.test(normalizePath(file));
}

function isMappedSourceFile(file) {
	const normalized = normalizePath(file);
	return (
		SOURCE_EXTENSIONS.has(pathExtension(normalized)) && !isTestFile(normalized)
	);
}

function comparePaths(left, right) {
	return left.localeCompare(right, "en");
}

function uniqueSorted(values) {
	return [...new Set(values)].sort(comparePaths);
}

function gitLsFiles(root, pathspecs = []) {
	const args = ["ls-files", "-z"];
	if (pathspecs.length > 0) args.push("--", ...pathspecs);
	const bytes = execFileSync("git", args, {
		cwd: root,
		encoding: "buffer",
		maxBuffer: 16 * 1024 * 1024,
		stdio: ["ignore", "pipe", "pipe"],
		windowsHide: true,
	});
	return bytes.toString("utf8").split("\0").filter(Boolean).map(normalizePath);
}

export function listMappedSourceFiles(root = process.cwd()) {
	return uniqueSorted(
		gitLsFiles(root, MAPPED_PATHS).filter(isMappedSourceFile),
	);
}

export function listTestFiles(root = process.cwd()) {
	return uniqueSorted(gitLsFiles(root).filter(isTestFile));
}

function hasModifier(node, kind) {
	return (
		ts.canHaveModifiers(node) &&
		(ts.getModifiers(node) ?? []).some((modifier) => modifier.kind === kind)
	);
}

function isExported(node) {
	return hasModifier(node, ts.SyntaxKind.ExportKeyword);
}

function isDefaultExported(node) {
	return hasModifier(node, ts.SyntaxKind.DefaultKeyword);
}

function propertyNameText(name, sourceFile) {
	if (!name) return null;
	if (ts.isIdentifier(name) || ts.isPrivateIdentifier(name)) return name.text;
	if (ts.isStringLiteral(name) || ts.isNumericLiteral(name)) return name.text;
	if (ts.isComputedPropertyName(name)) {
		return `[${name.expression.getText(sourceFile)}]`;
	}
	return name.getText(sourceFile);
}

function declarationLineRange(node, sourceFile) {
	const start =
		sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile)).line +
		1;
	const endPosition = Math.max(node.getStart(sourceFile), node.end - 1);
	const end = sourceFile.getLineAndCharacterOfPosition(endPosition).line + 1;
	return { lineStart: start, lineEnd: end };
}

function isCallableExpression(node) {
	return (
		node !== undefined &&
		(ts.isArrowFunction(node) ||
			ts.isFunctionExpression(node) ||
			ts.isClassExpression(node))
	);
}

function callableKindForVariable(declaration, isDefault) {
	const initializer = declaration.initializer;
	if (ts.isArrowFunction(initializer))
		return isDefault ? "default-arrow" : "arrow";
	if (ts.isFunctionExpression(initializer))
		return isDefault ? "default-function-expression" : "function-expression";
	if (ts.isClassExpression(initializer))
		return isDefault ? "default-class-expression" : "class-expression";
	return null;
}

function addEntry(entries, sourceFile, file, node, input) {
	if (!input.name) return null;
	const entry = {
		path: file,
		name: input.name,
		declarationName: input.declarationName ?? input.name,
		kind: input.kind,
		...declarationLineRange(node, sourceFile),
		exportNames: input.exportNames ?? [],
		ownerName: input.ownerName ?? null,
		memberName: input.memberName ?? null,
		memberStatic: Boolean(input.memberStatic),
	};
	entries.push(entry);
	return entry;
}

function hasStaticModifier(node) {
	return (
		node.modifiers?.some(
			(modifier) => modifier.kind === ts.SyntaxKind.StaticKeyword,
		) ?? false
	);
}

function addClassEntry(
	entries,
	sourceFile,
	file,
	declaration,
	name,
	defaultExport,
) {
	const ownerName = name ?? "default";
	const owner = addEntry(entries, sourceFile, file, declaration, {
		name: ownerName,
		declarationName: name ?? null,
		kind: defaultExport ? "default-class" : "class",
		exportNames: defaultExport
			? ["default"]
			: isExported(declaration)
				? [name]
				: [],
	});
	if (!owner) return null;
	for (const member of declaration.members) {
		if (
			!ts.isMethodDeclaration(member) &&
			!ts.isGetAccessorDeclaration(member) &&
			!ts.isSetAccessorDeclaration(member) &&
			!ts.isPropertyDeclaration(member)
		)
			continue;
		const memberName = propertyNameText(member.name, sourceFile);
		if (!memberName) continue;
		let kind;
		const staticMember = hasStaticModifier(member);
		if (ts.isGetAccessorDeclaration(member))
			kind = staticMember ? "static-getter" : "getter";
		else if (ts.isSetAccessorDeclaration(member))
			kind = staticMember ? "static-setter" : "setter";
		else if (ts.isMethodDeclaration(member))
			kind = staticMember ? "static-method" : "method";
		else {
			if (!member.initializer || !isCallableExpression(member.initializer))
				continue;
			kind = staticMember ? "static-property" : "property";
		}
		addEntry(entries, sourceFile, file, member, {
			name: `${ownerName}.${memberName}`,
			declarationName: memberName,
			kind,
			ownerName,
			memberName,
			memberStatic: staticMember,
		});
	}
	return owner;
}

function addExportAliases(entries, sourceFile) {
	const entriesByLocalName = new Map();
	for (const entry of entries) {
		if (entry.ownerName === null && entry.declarationName) {
			const current = entriesByLocalName.get(entry.declarationName) ?? [];
			current.push(entry);
			entriesByLocalName.set(entry.declarationName, current);
		}
	}
	for (const statement of sourceFile.statements) {
		if (
			ts.isExportDeclaration(statement) &&
			statement.exportClause &&
			ts.isNamedExports(statement.exportClause)
		) {
			for (const specifier of statement.exportClause.elements) {
				const local = (specifier.propertyName ?? specifier.name).text;
				const exported = specifier.name.text;
				for (const entry of entriesByLocalName.get(local) ?? [])
					entry.exportNames.push(exported);
			}
		}
		if (ts.isExportAssignment(statement) && !statement.isExportEquals) {
			if (ts.isIdentifier(statement.expression)) {
				for (const entry of entriesByLocalName.get(statement.expression.text) ??
					[])
					entry.exportNames.push("default");
			}
		}
	}
	for (const entry of entries)
		entry.exportNames = uniqueSorted(entry.exportNames);
}

export function parseCallables(file, source) {
	const normalizedFile = normalizePath(file);
	const sourceFile = ts.createSourceFile(
		normalizedFile,
		source,
		ts.ScriptTarget.Latest,
		true,
		normalizedFile.endsWith(".ts") || normalizedFile.endsWith(".tsx")
			? ts.ScriptKind.TS
			: ts.ScriptKind.JS,
	);
	const entries = [];
	for (const statement of sourceFile.statements) {
		if (ts.isFunctionDeclaration(statement)) {
			const name = statement.name?.text;
			if (!name && !isDefaultExported(statement)) continue;
			addEntry(entries, sourceFile, normalizedFile, statement, {
				name: name ?? "default",
				declarationName: name ?? null,
				kind: isDefaultExported(statement) ? "default-function" : "function",
				exportNames: isDefaultExported(statement)
					? ["default"]
					: isExported(statement)
						? [name]
						: [],
			});
			continue;
		}
		if (ts.isClassDeclaration(statement)) {
			const name = statement.name?.text;
			if (!name && !isDefaultExported(statement)) continue;
			addClassEntry(
				entries,
				sourceFile,
				normalizedFile,
				statement,
				name ?? null,
				isDefaultExported(statement),
			);
			continue;
		}
		if (ts.isVariableStatement(statement)) {
			for (const declaration of statement.declarationList.declarations) {
				if (!ts.isIdentifier(declaration.name)) continue;
				if (!isCallableExpression(declaration.initializer)) continue;
				const name = declaration.name.text;
				if (ts.isClassExpression(declaration.initializer)) {
					addClassEntry(
						entries,
						sourceFile,
						normalizedFile,
						declaration.initializer,
						name,
						false,
					);
				} else {
					addEntry(entries, sourceFile, normalizedFile, declaration, {
						name,
						kind: callableKindForVariable(declaration, false),
						exportNames: isExported(statement) ? [name] : [],
					});
				}
			}
			continue;
		}
		if (ts.isExportAssignment(statement) && !statement.isExportEquals) {
			const expression = statement.expression;
			if (isCallableExpression(expression)) {
				if (ts.isClassExpression(expression)) {
					addClassEntry(
						entries,
						sourceFile,
						normalizedFile,
						expression,
						expression.name?.text ?? null,
						true,
					);
				} else {
					addEntry(entries, sourceFile, normalizedFile, expression, {
						name: "default",
						declarationName: null,
						kind: ts.isArrowFunction(expression)
							? "default-arrow"
							: "default-function-expression",
						exportNames: ["default"],
					});
				}
			}
			continue;
		}
		if (ts.isExpressionStatement(statement)) {
			const assignment = statement.expression;
			if (
				ts.isBinaryExpression(assignment) &&
				assignment.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
				ts.isPropertyAccessExpression(assignment.left)
			) {
				const left = assignment.left;
				const leftName = propertyNameText(left.name, sourceFile);
				if (
					leftName === "exports" &&
					ts.isIdentifier(left.expression) &&
					left.expression.text === "module" &&
					isCallableExpression(assignment.right)
				) {
					if (ts.isClassExpression(assignment.right)) {
						addClassEntry(
							entries,
							sourceFile,
							normalizedFile,
							assignment.right,
							assignment.right.name?.text ?? null,
							true,
						);
					} else {
						addEntry(entries, sourceFile, normalizedFile, assignment, {
							name: "default",
							declarationName: null,
							kind: ts.isArrowFunction(assignment.right)
								? "default-arrow"
								: "default-function-expression",
							exportNames: ["default"],
						});
					}
				}
			}
		}
	}
	addExportAliases(entries, sourceFile);
	return entries.sort(
		(left, right) =>
			left.lineStart - right.lineStart ||
			left.lineEnd - right.lineEnd ||
			left.kind.localeCompare(right.kind, "en") ||
			left.name.localeCompare(right.name, "en"),
	);
}

function moduleCandidates(specifier, importer, root) {
	const normalized = specifier.replaceAll("\\", "/");
	const importerDirectory = path.posix.dirname(normalizePath(importer));
	const candidates = [];
	if (/^[A-Za-z]:\//.test(normalized) || path.posix.isAbsolute(normalized)) {
		candidates.push(
			normalizePath(path.relative(root, path.resolve(normalized))),
		);
	} else if (normalized.startsWith("./") || normalized.startsWith("../")) {
		candidates.push(
			path.posix.normalize(path.posix.join(importerDirectory, normalized)),
		);
	} else {
		candidates.push(normalized);
	}
	const result = [];
	for (const candidate of candidates) {
		result.push(candidate);
		for (const extension of MODULE_EXTENSIONS)
			result.push(`${candidate}${extension}`);
		for (const extension of MODULE_EXTENSIONS)
			result.push(path.posix.join(candidate, `index${extension}`));
	}
	return result;
}

function exportedEntriesByFile(entries) {
	const byFile = new Map();
	for (const entry of entries) {
		if (entry.ownerName !== null) continue;
		const fileEntries = byFile.get(entry.path) ?? new Map();
		for (const exportName of entry.exportNames)
			fileEntries.set(exportName, entry);
		byFile.set(entry.path, fileEntries);
	}
	return byFile;
}

function memberEntriesByOwner(entries) {
	const byOwner = new Map();
	for (const entry of entries) {
		if (entry.ownerName === null) continue;
		const key = `${entry.path}:${entry.ownerName}`;
		const members = byOwner.get(key) ?? [];
		members.push(entry);
		byOwner.set(key, members);
	}
	return { byOwner, key: (owner) => `${owner.path}:${owner.name}` };
}

function resolveImportedTarget(importsByLocal, name) {
	const targets = importsByLocal.get(name) ?? [];
	return targets.length === 1 ? targets[0] : null;
}

function classEntryFromExpression(
	expression,
	importsByLocal,
	namespaceImports,
) {
	if (ts.isParenthesizedExpression(expression))
		return classEntryFromExpression(
			expression.expression,
			importsByLocal,
			namespaceImports,
		);
	if (ts.isIdentifier(expression)) {
		const target = resolveImportedTarget(importsByLocal, expression.text);
		return target?.kind.includes("class") ? target : null;
	}
	if (
		ts.isPropertyAccessExpression(expression) &&
		ts.isIdentifier(expression.expression)
	) {
		const namespaceExports = namespaceImports.get(expression.expression.text);
		if (!namespaceExports) return null;
		const target = namespaceExports.get(expression.name.text);
		return target?.kind.includes("class") ? target : null;
	}
	return null;
}

function markCoverage(coverage, entry, testPath) {
	if (!entry) return;
	const key = `${entry.path}:${entry.lineStart}:${entry.kind}:${entry.name}`;
	const tests = coverage.get(key) ?? new Set();
	tests.add(testPath);
	coverage.set(key, tests);
}

function memberByName(
	membersByOwner,
	owner,
	memberName,
	{ staticMember } = {},
) {
	const members = membersByOwner.byOwner.get(membersByOwner.key(owner)) ?? [];
	return members.find(
		(member) =>
			member.memberName === memberName &&
			(staticMember === undefined || member.memberStatic === staticMember),
	);
}

function visit(node, callback) {
	callback(node);
	ts.forEachChild(node, (child) => visit(child, callback));
}

function resolveUrlNode(node, sourceFile, testPath) {
	if (!ts.isNewExpression(node) || node.arguments?.length !== 2) return null;
	const [specifier, base] = node.arguments;
	if (!ts.isStringLiteral(specifier)) return null;
	if (base.getText(sourceFile) !== "import.meta.url") return null;
	return path.posix.normalize(
		path.posix.join(
			path.posix.dirname(normalizePath(testPath)),
			specifier.text,
		),
	);
}

function resolveStringValues(node, context) {
	const { sourceFile, constants, seen } = context;
	if (!node) return [];
	if (ts.isParenthesizedExpression(node))
		return resolveStringValues(node.expression, context);
	if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))
		return [node.text];
	if (ts.isTemplateExpression(node)) {
		let value = node.head.text;
		for (const span of node.templateSpans) {
			const values = resolveStringValues(span.expression, context);
			if (values.length !== 1) return [];
			value += values[0] + span.literal.text;
		}
		return [value];
	}
	if (ts.isIdentifier(node)) {
		if (seen.has(node.text)) return [];
		const initializer = constants.get(node.text);
		if (!initializer) return [];
		return resolveStringValues(initializer, {
			...context,
			seen: new Set([...seen, node.text]),
		});
	}
	if (ts.isCallExpression(node)) {
		if (
			ts.isPropertyAccessExpression(node.expression) &&
			(node.expression.name.text === "join" ||
				node.expression.name.text === "resolve")
		) {
			const values = [];
			for (const argument of node.arguments) {
				const resolved = resolveStringValues(argument, context);
				if (resolved.length !== 1) return [];
				values.push(resolved[0]);
			}
			if (values.length === 0) return [];
			return [
				node.expression.name.text === "resolve"
					? path.posix.resolve(...values)
					: path.posix.join(...values),
			];
		}
		if (
			node.expression.getText(sourceFile) === "fileURLToPath" &&
			node.arguments.length === 1
		) {
			const resolved = resolveUrlNode(
				node.arguments[0],
				sourceFile,
				context.testPath,
			);
			return resolved ? [resolved] : [];
		}
		if (node.expression.getText(sourceFile) === "process.cwd()") return ["."];
	}
	if (ts.isNewExpression(node)) {
		const resolved = resolveUrlNode(node, sourceFile, context.testPath);
		return resolved ? [resolved] : [];
	}
	return [];
}

function resolveStringArray(node, context) {
	if (ts.isArrayLiteralExpression(node)) {
		const values = [];
		for (const element of node.elements) {
			if (ts.isSpreadElement(element)) continue;
			const resolved = resolveStringValues(element, context);
			if (resolved.length === 1) values.push(resolved[0]);
		}
		return values;
	}
	if (ts.isIdentifier(node)) {
		const initializer = context.constants.get(node.text);
		if (!initializer) return [];
		return ts.isArrayLiteralExpression(initializer)
			? resolveStringArray(initializer, context)
			: resolveStringValues(initializer, context);
	}
	return [];
}

function repositoryRelative(value, root, testPath) {
	const normalized = normalizePath(value);
	const rootNormalized = normalizePath(path.resolve(root));
	const rootWithoutDrive = rootNormalized.replace(/^[A-Za-z]:/, "");
	if (normalized.startsWith(`${rootWithoutDrive}/`))
		return normalized.slice(rootWithoutDrive.length + 1);
	if (/^[A-Za-z]:\//.test(normalized) || normalized.startsWith("/"))
		return normalizePath(path.relative(root, path.resolve(normalized)));
	if (normalized.startsWith("."))
		return path.posix.normalize(
			path.posix.join(path.posix.dirname(normalizePath(testPath)), normalized),
		);
	return normalized;
}

function buildStaticContext(
	sourceFile,
	importsByLocal,
	namespaceImports,
	testPath,
) {
	const constants = new Map();
	const instances = new Map();
	visit(sourceFile, (node) => {
		if (
			!ts.isVariableDeclaration(node) ||
			!ts.isIdentifier(node.name) ||
			!node.initializer
		)
			return;
		if (ts.isNewExpression(node.initializer)) {
			const target = classEntryFromExpression(
				node.initializer.expression,
				importsByLocal,
				namespaceImports,
			);
			if (target) instances.set(node.name.text, target);
			return;
		}
		const values = resolveStringValues(node.initializer, {
			sourceFile,
			constants,
			seen: new Set(),
			testPath,
		});
		if (values.length > 0) constants.set(node.name.text, node.initializer);
	});
	return { constants, instances };
}

function childProcessImports(sourceFile) {
	const names = new Set();
	for (const statement of sourceFile.statements) {
		if (
			!ts.isImportDeclaration(statement) ||
			!ts.isStringLiteral(statement.moduleSpecifier) ||
			statement.moduleSpecifier.text !== "node:child_process"
		)
			continue;
		const bindings = statement.importClause?.namedBindings;
		if (!bindings || !ts.isNamedImports(bindings)) continue;
		for (const element of bindings.elements) {
			if (CHILD_PROCESS_FUNCTIONS.has(element.name.text))
				names.add(element.name.text);
		}
	}
	return names;
}

function commandCoverage(sourceFile, root, testPath, sourceFiles, constants) {
	const result = new Set();
	const childProcess = childProcessImports(sourceFile);
	if (childProcess.size === 0) return result;
	visit(sourceFile, (node) => {
		if (!ts.isCallExpression(node) || !ts.isIdentifier(node.expression)) return;
		if (!childProcess.has(node.expression.text)) return;
		for (const argument of node.arguments) {
			if (!ts.isArrayLiteralExpression(argument) && !ts.isIdentifier(argument))
				continue;
			const candidates = resolveStringArray(argument, {
				sourceFile,
				constants,
				seen: new Set(),
				testPath,
			});
			for (const candidate of candidates) {
				const relative = repositoryRelative(candidate, root, testPath);
				if (sourceFiles.has(relative)) result.add(relative);
			}
		}
	});
	return result;
}

async function analyzeTests({
	root,
	files,
	testFiles,
	exportsByFile,
	membersByOwner,
}) {
	const sourceSet = new Set(files);
	const coverage = new Map();
	const commandCoverageByFile = new Map();
	const testSources = await Promise.all(
		testFiles.map(async (testPath) => ({
			testPath,
			text: await readFile(path.join(root, testPath), "utf8"),
		})),
	);
	for (const { testPath, text } of testSources) {
		const sourceFile = ts.createSourceFile(
			testPath,
			text,
			ts.ScriptTarget.Latest,
			true,
			testPath.endsWith(".ts") || testPath.endsWith(".tsx")
				? ts.ScriptKind.TS
				: ts.ScriptKind.JS,
		);
		const importsByLocal = new Map();
		const namespaceImports = new Map();
		for (const statement of sourceFile.statements) {
			if (
				!ts.isImportDeclaration(statement) ||
				!ts.isStringLiteral(statement.moduleSpecifier) ||
				statement.importClause?.isTypeOnly
			)
				continue;
			const targetFile = moduleCandidates(
				statement.moduleSpecifier.text,
				testPath,
				root,
			).find((candidate) => sourceSet.has(candidate));
			if (!targetFile) continue;
			const targetExports = exportsByFile.get(targetFile) ?? new Map();
			const clause = statement.importClause;
			if (clause?.name) {
				const target = targetExports.get("default");
				if (target) importsByLocal.set(clause.name.text, [target]);
			}
			const bindings = clause?.namedBindings;
			if (bindings && ts.isNamespaceImport(bindings))
				namespaceImports.set(bindings.name.text, targetExports);
			if (bindings && ts.isNamedImports(bindings)) {
				for (const element of bindings.elements) {
					if (element.isTypeOnly) continue;
					const imported = (element.propertyName ?? element.name).text;
					const target = targetExports.get(imported);
					if (target) importsByLocal.set(element.name.text, [target]);
				}
			}
		}
		const staticContext = buildStaticContext(
			sourceFile,
			importsByLocal,
			namespaceImports,
			testPath,
		);
		for (const source of commandCoverage(
			sourceFile,
			root,
			testPath,
			sourceSet,
			staticContext.constants,
		)) {
			const tests = commandCoverageByFile.get(source) ?? new Set();
			tests.add(testPath);
			commandCoverageByFile.set(source, tests);
		}
		const markMember = (owner, name, staticMember) => {
			markCoverage(
				coverage,
				memberByName(membersByOwner, owner, name, { staticMember }),
				testPath,
			);
		};
		visit(sourceFile, (node) => {
			if (ts.isNewExpression(node)) {
				markCoverage(
					coverage,
					classEntryFromExpression(
						node.expression,
						importsByLocal,
						namespaceImports,
					),
					testPath,
				);
			}
			if (ts.isCallExpression(node)) {
				if (ts.isIdentifier(node.expression)) {
					markCoverage(
						coverage,
						resolveImportedTarget(importsByLocal, node.expression.text),
						testPath,
					);
				} else if (ts.isPropertyAccessExpression(node.expression)) {
					const access = node.expression;
					const name = propertyNameText(access.name, sourceFile);
					if (ts.isIdentifier(access.expression)) {
						const namespaceTarget = namespaceImports
							.get(access.expression.text)
							?.get(name);
						if (namespaceTarget)
							markCoverage(coverage, namespaceTarget, testPath);
						const owner = resolveImportedTarget(
							importsByLocal,
							access.expression.text,
						);
						if (owner?.kind.includes("class")) markMember(owner, name, true);
						const instance = staticContext.instances.get(
							access.expression.text,
						);
						if (instance) markMember(instance, name, false);
					}
					if (ts.isNewExpression(access.expression)) {
						const owner = classEntryFromExpression(
							access.expression.expression,
							importsByLocal,
							namespaceImports,
						);
						if (owner) markMember(owner, name, false);
					}
				}
				return;
			}
			if (ts.isPropertyAccessExpression(node)) {
				if (!ts.isIdentifier(node.expression)) return;
				const owner = staticContext.instances.get(node.expression.text);
				if (!owner) return;
				const name = propertyNameText(node.name, sourceFile);
				const parent = node.parent;
				if (
					ts.isBinaryExpression(parent) &&
					parent.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
					parent.left === node
				)
					markMember(owner, name, false);
				else markMember(owner, name, false);
			}
		});
	}
	return { coverage, commandCoverageByFile };
}

function entryKey(entry) {
	return `${entry.path}:${entry.lineStart}:${entry.kind}:${entry.name}`;
}

function formatEntry(entry) {
	const tests =
		entry.tests.length === 0
			? "none"
			: entry.tests.map((test) => `\`${test}\``).join(", ");
	return `- \`${entry.name}\` [${entry.kind}] L${entry.lineStart}-L${entry.lineEnd}; tests: ${tests}`;
}

function formatToolingMap(files) {
	const callables = files.flatMap((file) => file.callables);
	const uncovered = callables.filter((entry) => entry.tests.length === 0);
	const lines = [
		HEADER,
		"",
		`Counts: ${files.length} files, ${callables.length} callables, ${uncovered.length} without a covering test.`,
	];
	for (const file of files) {
		lines.push("", `## \`${file.path}\``, "");
		if (file.callables.length === 0) lines.push("- No top-level callables.");
		for (const entry of file.callables) lines.push(formatEntry(entry));
		if (file.commandTests.length > 0) {
			lines.push(
				`- Command run by: ${file.commandTests
					.map((test) => `\`${test}\``)
					.join(", ")}`,
			);
		}
	}
	return `${lines.join("\n")}\n`;
}

export async function buildToolingMap({ root = process.cwd() } = {}) {
	const repositoryRoot = path.resolve(root);
	const files = listMappedSourceFiles(repositoryRoot);
	const testFiles = listTestFiles(repositoryRoot);
	const parsedByFile = await Promise.all(
		files.map(async (file) => ({
			path: file,
			callables: parseCallables(
				file,
				await readFile(path.join(repositoryRoot, file), "utf8"),
			),
		})),
	);
	const allCallables = parsedByFile.flatMap((file) => file.callables);
	const exportsByFile = exportedEntriesByFile(allCallables);
	const membersByOwner = memberEntriesByOwner(allCallables);
	const { coverage, commandCoverageByFile } = await analyzeTests({
		root: repositoryRoot,
		files,
		testFiles,
		exportsByFile,
		membersByOwner,
	});
	for (const entry of allCallables)
		entry.tests = uniqueSorted(coverage.get(entryKey(entry)) ?? []);
	const mappedFiles = parsedByFile.map((file) => ({
		path: file.path,
		callables: file.callables,
		commandTests: uniqueSorted(commandCoverageByFile.get(file.path) ?? []),
	}));
	const callables = mappedFiles.flatMap((file) => file.callables);
	return {
		root: repositoryRoot,
		text: formatToolingMap(mappedFiles),
		files: mappedFiles,
		callables,
		uncovered: callables.filter((entry) => entry.tests.length === 0),
	};
}

export async function writeToolingMap({ root = process.cwd() } = {}) {
	const built = await buildToolingMap({ root });
	const target = path.join(built.root, MAP_RELATIVE_PATH);
	await mkdir(path.dirname(target), { recursive: true });
	await writeFile(target, built.text, "utf8");
	console.log(
		`Wrote ${MAP_RELATIVE_PATH}: ${built.files.length} files, ${built.callables.length} callables, ${built.uncovered.length} without a covering test.`,
	);
	return built;
}

function parseTestList(value) {
	if (value === "none") return [];
	return uniqueSorted(
		[...value.matchAll(/`([^`]+)`/g)].map((match) => match[1]),
	);
}

export function parseToolingMap(text) {
	const files = [];
	let current = null;
	for (const rawLine of String(text).replace(/\r\n?/g, "\n").split("\n")) {
		const fileMatch = rawLine.match(/^## `([^`]+)`$/);
		if (fileMatch) {
			current = { path: fileMatch[1], callables: [], commandTests: [] };
			files.push(current);
			continue;
		}
		if (!current) continue;
		const commandMatch = rawLine.match(/^- Command run by: (.+)$/);
		if (commandMatch) {
			current.commandTests = parseTestList(commandMatch[1]);
			continue;
		}
		const entryMatch = rawLine.match(
			/^- `([^`]+)` \[([^\]]+)\] L(\d+)-L(\d+); tests: (.+)$/,
		);
		if (entryMatch) {
			current.callables.push({
				path: current.path,
				name: entryMatch[1],
				kind: entryMatch[2],
				lineStart: Number(entryMatch[3]),
				lineEnd: Number(entryMatch[4]),
				tests: parseTestList(entryMatch[5]),
			});
		}
	}
	return files;
}

function setsEqual(left, right) {
	return (
		left.length === right.length &&
		left.every((value, index) => value === right[index])
	);
}

function listDifference(left, right) {
	const rightSet = new Set(right);
	return left.filter((value) => !rightSet.has(value));
}

export async function validateToolingMap({ root = process.cwd(), text } = {}) {
	const repositoryRoot = path.resolve(root);
	const committed =
		text ??
		(await readFile(path.join(repositoryRoot, MAP_RELATIVE_PATH), "utf8"));
	const expected = await buildToolingMap({ root: repositoryRoot });
	const parsed = parseToolingMap(committed);
	const trackedTests = new Set(listTestFiles(repositoryRoot));
	const errors = [];
	const expectedPaths = expected.files.map((file) => file.path);
	const parsedPaths = parsed.map((file) => file.path);
	if (!setsEqual(expectedPaths, parsedPaths)) {
		const missing = listDifference(expectedPaths, parsedPaths);
		const extra = listDifference(parsedPaths, expectedPaths);
		errors.push(
			`file list differs: missing [${missing.join(", ")}]; extra [${extra.join(", ")}]`,
		);
	}
	const parsedEntries = parsed.flatMap((file) => file.callables);
	const expectedEntries = expected.callables;
	for (const entry of parsedEntries) {
		const match = expectedEntries.find(
			(candidate) =>
				candidate.path === entry.path &&
				candidate.name === entry.name &&
				candidate.kind === entry.kind &&
				candidate.lineStart === entry.lineStart &&
				candidate.lineEnd === entry.lineEnd,
		);
		if (!match) {
			errors.push(
				`line range differs for ${entry.path} ${entry.name} [${entry.kind}]`,
			);
			continue;
		}
		if (!setsEqual(match.tests, entry.tests)) {
			errors.push(
				`test coverage differs for ${entry.path} ${entry.name} [${entry.kind}]`,
			);
		}
		for (const test of entry.tests) {
			if (!trackedTests.has(test)) {
				errors.push(`test file is missing or untracked: ${test}`);
				continue;
			}
			if (!match.tests.includes(test))
				errors.push(
					`test call evidence is missing for ${entry.path} ${entry.name}: ${test}`,
				);
		}
	}
	if (parsedEntries.length !== expectedEntries.length) {
		errors.push(
			`callable list differs: expected ${expectedEntries.length}, found ${parsedEntries.length}`,
		);
	}
	return { ok: errors.length === 0, errors, expected, parsed };
}

function firstDifference(committed, generated) {
	const committedLines = committed.replace(/\r\n?/g, "\n").split("\n");
	const generatedLines = generated.split("\n");
	const length = Math.max(committedLines.length, generatedLines.length);
	for (let index = 0; index < length; index += 1) {
		if (committedLines[index] !== generatedLines[index])
			return `line ${index + 1} differs`;
	}
	return "content differs";
}

export async function checkToolingMap({ root = process.cwd() } = {}) {
	const repositoryRoot = path.resolve(root);
	const generated = await buildToolingMap({ root: repositoryRoot });
	let committed;
	try {
		committed = await readFile(
			path.join(repositoryRoot, MAP_RELATIVE_PATH),
			"utf8",
		);
	} catch (error) {
		if (error?.code !== "ENOENT") throw error;
		return {
			ok: false,
			errors: [`map file is missing: ${MAP_RELATIVE_PATH}`],
			generated,
			committed: null,
		};
	}
	if (committed.replace(/\r\n?/g, "\n") === generated.text)
		return { ok: true, errors: [], generated, committed };
	const parsed = parseToolingMap(committed);
	const expectedPaths = generated.files.map((file) => file.path);
	const actualPaths = parsed.map((file) => file.path);
	const errors = [];
	if (!setsEqual(expectedPaths, actualPaths)) {
		const missing = listDifference(expectedPaths, actualPaths);
		const extra = listDifference(actualPaths, expectedPaths);
		errors.push(
			`file list differs: missing [${missing.join(", ")}]; extra [${extra.join(", ")}]`,
		);
	} else {
		errors.push(
			`generated map differs (${firstDifference(committed, generated.text)})`,
		);
	}
	return { ok: false, errors, generated, committed };
}

function usage() {
	console.log(`Usage: pnpm map:tooling [--check]

Writes ${MAP_RELATIVE_PATH} from tracked JavaScript and TypeScript in the mapped tool paths.
Use --check to regenerate in memory and fail when the committed map differs.

Exit codes:
  0  map written or committed map is current
  1  invalid option, missing map, or drift`);
}

async function main(args = process.argv.slice(2)) {
	if (args.includes("--help") || args.includes("-h")) {
		usage();
		return;
	}
	if (args.length > 1 || (args.length === 1 && args[0] !== "--check"))
		throw new Error(`Unknown option: ${args.join(" ")}`);
	if (args[0] === "--check") {
		const result = await checkToolingMap();
		if (!result.ok) {
			console.error(
				`${CHECK_COMMAND}: FAIL: ${result.errors[0]} (run ${REGENERATE_COMMAND})`,
			);
			process.exitCode = 1;
			return;
		}
		console.log(
			`${CHECK_COMMAND} passed: ${result.generated.files.length} files, ${result.generated.callables.length} callables, ${result.generated.uncovered.length} without a covering test.`,
		);
		return;
	}
	await writeToolingMap();
}

const isMain =
	process.argv[1] !== undefined &&
	import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
	main().catch((error) => {
		const command = process.argv.includes("--check")
			? CHECK_COMMAND
			: REGENERATE_COMMAND;
		console.error(
			`${command}: FAIL: ${error.message} (run ${REGENERATE_COMMAND})`,
		);
		process.exitCode = 1;
	});
}
