// Build, write, and compare the generated agent-tooling code map.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import {
	CHECK_COMMAND,
	describeMappedFiles,
	listMappedSourceFiles,
	listUntrackedMappedSourceFiles,
	MAP_RELATIVE_PATH,
	REGENERATE_COMMAND,
} from "./tooling-map-parser.mjs";

export { CHECK_COMMAND, MAP_RELATIVE_PATH, REGENERATE_COMMAND };

const HEADER = `# Agent tooling code map

Generated by \`${REGENERATE_COMMAND}\` from tracked JavaScript and TypeScript under the mapped tool paths. Do not edit by hand.`;

function folderOf(file) {
	return path.posix.dirname(file.path);
}

function formatEntry(file) {
	const exports =
		file.exports.length === 0
			? "none"
			: file.exports.map((name) => `\`${name}\``).join(", ");
	return `- \`${path.posix.basename(file.path)}\`: ${file.leadingComment} Exports: ${exports}.`;
}

function countWithoutLeadingComment(files) {
	return files.filter((file) => file.leadingComment === "(no leading comment)")
		.length;
}

function formatToolingMap(files, withoutLeadingComment) {
	const filesByFolder = new Map();
	for (const file of files) {
		const folder = folderOf(file);
		const entries = filesByFolder.get(folder) ?? [];
		entries.push(file);
		filesByFolder.set(folder, entries);
	}
	const lines = [
		HEADER,
		"",
		`Counts: ${files.length} files, ${withoutLeadingComment} without a leading comment.`,
	];
	for (const [folder, entries] of filesByFolder) {
		lines.push("", `## \`${folder}\``);
		for (const file of entries) lines.push(formatEntry(file));
	}
	return `${lines.join("\n")}\n`;
}

async function readMappedSources(repositoryRoot, files) {
	const sourcesByFile = new Map();
	for (const file of files)
		sourcesByFile.set(
			file,
			await readFile(path.join(repositoryRoot, file), "utf8"),
		);
	return sourcesByFile;
}

export async function buildToolingMap({ root = process.cwd() } = {}) {
	const repositoryRoot = path.resolve(root);
	const files = listMappedSourceFiles(repositoryRoot);
	const sourcesByFile = await readMappedSources(repositoryRoot, files);
	const describedFiles = describeMappedFiles({
		root: repositoryRoot,
		files,
		sourcesByFile,
	});
	const withoutLeadingComment = countWithoutLeadingComment(describedFiles);
	return {
		root: repositoryRoot,
		text: formatToolingMap(describedFiles, withoutLeadingComment),
		files: describedFiles,
		withoutLeadingComment,
	};
}

export async function writeToolingMap({ root = process.cwd() } = {}) {
	const built = await buildToolingMap({ root });
	const target = path.join(built.root, MAP_RELATIVE_PATH);
	await mkdir(path.dirname(target), { recursive: true });
	await writeFile(target, built.text, "utf8");
	console.log(
		`Wrote ${MAP_RELATIVE_PATH}: ${built.files.length} files, ${built.withoutLeadingComment} without a leading comment.`,
	);
	return built;
}

function parseToolingMap(text) {
	const files = [];
	let folder = null;
	for (const line of String(text).replace(/\r\n?/g, "\n").split("\n")) {
		const folderMatch = line.match(/^## `([^`]+)`$/);
		if (folderMatch) {
			folder = folderMatch[1];
			continue;
		}
		const fileMatch = line.match(/^- `([^`]+)`: /);
		if (fileMatch) {
			files.push({
				path: folder ? path.posix.join(folder, fileMatch[1]) : fileMatch[1],
				folder,
				text: line,
			});
		}
	}
	return files;
}

function listDifference(left, right) {
	const rightSet = new Set(right);
	return left.filter((value) => !rightSet.has(value));
}

function fileListDifference(expectedFiles, parsedFiles) {
	const expectedPaths = expectedFiles.map((file) => file.path);
	const parsedPaths = parsedFiles.map((file) => file.path);
	const missing = listDifference(expectedPaths, parsedPaths);
	const extra = listDifference(parsedPaths, expectedPaths);
	if (missing.length === 0 && extra.length === 0) return null;
	return `file list differs: missing [${missing.join(", ")}]; extra [${extra.join(", ")}]`;
}

function entryDifferences(expectedFiles, parsedFiles) {
	const parsedByPath = new Map(parsedFiles.map((file) => [file.path, file]));
	const errors = [];
	for (const expectedFile of expectedFiles) {
		const parsedFile = parsedByPath.get(expectedFile.path);
		if (!parsedFile) continue;
		const expectedFolder = folderOf(expectedFile);
		const expectedText = formatEntry(expectedFile);
		if (
			parsedFile.folder !== expectedFolder ||
			parsedFile.text !== expectedText
		)
			errors.push(
				`generated entry differs for ${expectedFile.path}: expected "${expectedText}", found "${parsedFile.text}" in folder ${parsedFile.folder}`,
			);
	}
	return errors;
}

function mapDifferences(expectedFiles, parsedFiles) {
	const errors = [];
	const fileListError = fileListDifference(expectedFiles, parsedFiles);
	if (fileListError) errors.push(fileListError);
	errors.push(...entryDifferences(expectedFiles, parsedFiles));
	return errors;
}

export async function checkToolingMap({ root = process.cwd() } = {}) {
	const repositoryRoot = path.resolve(root);
	const untracked = listUntrackedMappedSourceFiles(repositoryRoot);
	if (untracked.length > 0) {
		return {
			ok: false,
			errors: untracked.map((file) => `untracked mapped source file: ${file}`),
			generated: null,
			committed: null,
		};
	}
	const generated = await buildToolingMap({ root: repositoryRoot });
	let committed;
	try {
		committed = await readFile(
			path.join(repositoryRoot, MAP_RELATIVE_PATH),
			"utf8",
		);
	} catch (error) {
		if (error?.code !== "ENOENT") throw error;
		return {
			ok: false,
			errors: [`map file is missing: ${MAP_RELATIVE_PATH}`],
			generated,
			committed: null,
		};
	}
	if (committed.replace(/\r\n?/g, "\n") === generated.text)
		return { ok: true, errors: [], generated, committed };
	const parsed = parseToolingMap(committed);
	const differences = mapDifferences(generated.files, parsed);
	if (differences.length === 0) differences.push("content differs");
	return {
		ok: false,
		errors: [`generated map differs: ${differences.join("; ")}`],
		generated,
		committed,
	};
}
