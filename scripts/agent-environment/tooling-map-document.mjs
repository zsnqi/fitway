import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { analyzeCoverage } from "./tooling-map-coverage.mjs";
import {
	CHECK_COMMAND,
	listMappedSourceFiles,
	listTestFiles,
	listUntrackedMappedSourceFiles,
	MAP_RELATIVE_PATH,
	normalizePath,
	parseCallables,
	REGENERATE_COMMAND,
	uniqueSorted,
} from "./tooling-map-parser.mjs";

export { CHECK_COMMAND, MAP_RELATIVE_PATH, REGENERATE_COMMAND };

const HEADER = `# Agent tooling code map

Generated by \`${REGENERATE_COMMAND}\` from tracked JavaScript and TypeScript under the mapped tool paths. Do not edit by hand.`;

function entryKey(entry) {
	return `${entry.path}:${entry.lineStart}:${entry.kind}:${entry.name}`;
}

function formatEntry(entry) {
	const tests =
		entry.tests.length === 0
			? "none"
			: entry.tests.map((test) => `\`${test}\``).join(", ");
	return `- \`${entry.name}\` [${entry.kind}] L${entry.lineStart}-L${entry.lineEnd}; tests: ${tests}`;
}

function formatToolingMap(files) {
	const callables = files.flatMap((file) => file.callables);
	const uncovered = callables.filter((entry) => entry.tests.length === 0);
	const lines = [
		HEADER,
		"",
		`Counts: ${files.length} files, ${callables.length} callables, ${uncovered.length} without a covering test.`,
	];
	for (const file of files) {
		lines.push("", `## \`${file.path}\``, "");
		if (file.callables.length === 0) lines.push("- No top-level callables.");
		for (const entry of file.callables) lines.push(formatEntry(entry));
		if (file.commandTests.length > 0) {
			lines.push(
				`- Command run by: ${file.commandTests
					.map((test) => `\`${test}\``)
					.join(", ")}`,
			);
		}
	}
	return `${lines.join("\n")}\n`;
}

async function readMappedSources(repositoryRoot, files) {
	const sourcesByFile = new Map();
	for (const file of files)
		sourcesByFile.set(
			file,
			await readFile(path.join(repositoryRoot, file), "utf8"),
		);
	return sourcesByFile;
}

async function packageNodeScripts(repositoryRoot, sourceFiles) {
	let packageJson;
	try {
		packageJson = JSON.parse(
			await readFile(path.join(repositoryRoot, "package.json"), "utf8"),
		);
	} catch (error) {
		if (error?.code === "ENOENT") return new Map();
		throw error;
	}
	const result = new Map();
	for (const [name, command] of Object.entries(packageJson.scripts ?? {})) {
		const match = /^node\s+(?:"([^"]+)"|'([^']+)'|(\S+))/.exec(
			String(command).trim(),
		);
		if (!match) continue;
		const modulePath = normalizePath(match[1] ?? match[2] ?? match[3]);
		if (sourceFiles.has(modulePath)) result.set(name, modulePath);
	}
	return result;
}

export async function buildToolingMap({ root = process.cwd() } = {}) {
	const repositoryRoot = path.resolve(root);
	const files = listMappedSourceFiles(repositoryRoot);
	const testFiles = listTestFiles(repositoryRoot);
	const sourcesByFile = await readMappedSources(repositoryRoot, files);
	const packageScripts = await packageNodeScripts(
		repositoryRoot,
		new Set(files),
	);
	const parsedByFile = files.map((file) => ({
		path: file,
		callables: parseCallables(file, sourcesByFile.get(file) ?? ""),
	}));
	const { coverage, commandCoverageByFile } = await analyzeCoverage({
		root: repositoryRoot,
		files,
		testFiles,
		parsedByFile,
		sourcesByFile,
		packageScripts,
	});
	for (const file of parsedByFile) {
		for (const entry of file.callables)
			entry.tests = uniqueSorted(coverage.get(entryKey(entry)) ?? []);
	}
	const mappedFiles = parsedByFile.map((file) => ({
		path: file.path,
		callables: file.callables,
		commandTests: uniqueSorted(commandCoverageByFile.get(file.path) ?? []),
	}));
	const callables = mappedFiles.flatMap((file) => file.callables);
	return {
		root: repositoryRoot,
		text: formatToolingMap(mappedFiles),
		files: mappedFiles,
		callables,
		uncovered: callables.filter((entry) => entry.tests.length === 0),
	};
}

export async function writeToolingMap({ root = process.cwd() } = {}) {
	const built = await buildToolingMap({ root });
	const target = path.join(built.root, MAP_RELATIVE_PATH);
	await mkdir(path.dirname(target), { recursive: true });
	await writeFile(target, built.text, "utf8");
	console.log(
		`Wrote ${MAP_RELATIVE_PATH}: ${built.files.length} files, ${built.callables.length} callables, ${built.uncovered.length} without a covering test.`,
	);
	return built;
}

function parseTestList(value) {
	if (value === "none") return [];
	return uniqueSorted(
		[...value.matchAll(/`([^`]+)`/g)].map((match) => match[1]),
	);
}

export function parseToolingMap(text) {
	const files = [];
	let current = null;
	for (const rawLine of String(text).replace(/\r\n?/g, "\n").split("\n")) {
		const fileMatch = rawLine.match(/^## `([^`]+)`$/);
		if (fileMatch) {
			current = {
				path: fileMatch[1],
				callables: [],
				commandTests: [],
			};
			files.push(current);
			continue;
		}
		if (!current) continue;
		const commandMatch = rawLine.match(/^- Command run by: (.+)$/);
		if (commandMatch) {
			current.commandTests = parseTestList(commandMatch[1]);
			continue;
		}
		const entryMatch = rawLine.match(
			/^- `([^`]+)` \[([^\]]+)\] L(\d+)-L(\d+); tests: (.+)$/,
		);
		if (entryMatch) {
			current.callables.push({
				path: current.path,
				name: entryMatch[1],
				kind: entryMatch[2],
				lineStart: Number(entryMatch[3]),
				lineEnd: Number(entryMatch[4]),
				tests: parseTestList(entryMatch[5]),
			});
		}
	}
	return files;
}

function setsEqual(left, right) {
	return (
		left.length === right.length &&
		left.every((value, index) => value === right[index])
	);
}

function listDifference(left, right) {
	const rightSet = new Set(right);
	return left.filter((value) => !rightSet.has(value));
}

function fileListDifference(expectedFiles, parsedFiles) {
	const expectedPaths = expectedFiles.map((file) => file.path);
	const parsedPaths = parsedFiles.map((file) => file.path);
	if (setsEqual(expectedPaths, parsedPaths)) return null;
	const missing = listDifference(expectedPaths, parsedPaths);
	const extra = listDifference(parsedPaths, expectedPaths);
	return `file list differs: missing [${missing.join(", ")}]; extra [${extra.join(", ")}]`;
}

function diffCommandTests(expectedFile, parsedFile) {
	const missing = listDifference(
		expectedFile.commandTests,
		parsedFile.commandTests,
	);
	const extra = listDifference(
		parsedFile.commandTests,
		expectedFile.commandTests,
	);
	return [
		...missing.map(
			(test) =>
				`command test coverage differs for ${expectedFile.path}: missing command test relation for ${expectedFile.path}: ${test}`,
		),
		...extra.map(
			(test) =>
				`command test coverage differs for ${expectedFile.path}: extra command test relation for ${expectedFile.path}: ${test}`,
		),
	];
}

function callableIdentity(entry) {
	return `${entry.path}\0${entry.name}\0${entry.kind}`;
}

function diffCallables(expectedFiles, parsedFiles) {
	const expected = new Map(
		expectedFiles
			.flatMap((file) => file.callables)
			.map((entry) => [callableIdentity(entry), entry]),
	);
	const parsed = new Map(
		parsedFiles
			.flatMap((file) => file.callables)
			.map((entry) => [callableIdentity(entry), entry]),
	);
	const errors = [];
	for (const [identity, entry] of expected) {
		const parsedEntry = parsed.get(identity);
		if (!parsedEntry) {
			errors.push(
				`missing callable ${entry.path} ${entry.name} [${entry.kind}]`,
			);
			continue;
		}
		if (
			entry.lineStart !== parsedEntry.lineStart ||
			entry.lineEnd !== parsedEntry.lineEnd
		) {
			errors.push(
				`callable range differs for ${entry.path} ${entry.name} [${entry.kind}]: expected L${entry.lineStart}-L${entry.lineEnd}, found L${parsedEntry.lineStart}-L${parsedEntry.lineEnd}`,
			);
			continue;
		}
		if (!setsEqual(entry.tests, parsedEntry.tests)) {
			errors.push(
				`test coverage differs for ${entry.path} ${entry.name} [${entry.kind}]`,
			);
		}
	}
	for (const [identity, entry] of parsed) {
		if (!expected.has(identity))
			errors.push(`extra callable ${entry.path} ${entry.name} [${entry.kind}]`);
	}
	return errors;
}

function diffToolingMaps(expectedFiles, parsedFiles) {
	const errors = [];
	const fileListError = fileListDifference(expectedFiles, parsedFiles);
	if (fileListError) errors.push(fileListError);
	const parsedByPath = new Map(parsedFiles.map((file) => [file.path, file]));
	for (const expectedFile of expectedFiles) {
		const parsedFile = parsedByPath.get(expectedFile.path);
		if (parsedFile) errors.push(...diffCommandTests(expectedFile, parsedFile));
	}
	errors.push(...diffCallables(expectedFiles, parsedFiles));
	return errors;
}

export async function validateToolingMap({ root = process.cwd(), text } = {}) {
	const repositoryRoot = path.resolve(root);
	const committed =
		text ??
		(await readFile(path.join(repositoryRoot, MAP_RELATIVE_PATH), "utf8"));
	const expected = await buildToolingMap({ root: repositoryRoot });
	const parsed = parseToolingMap(committed);
	const errors = diffToolingMaps(expected.files, parsed);
	return { ok: errors.length === 0, errors, expected, parsed };
}

export async function checkToolingMap({ root = process.cwd() } = {}) {
	const repositoryRoot = path.resolve(root);
	const untracked = listUntrackedMappedSourceFiles(repositoryRoot);
	if (untracked.length > 0) {
		return {
			ok: false,
			errors: untracked.map((file) => `untracked mapped source file: ${file}`),
			generated: null,
			committed: null,
		};
	}
	const generated = await buildToolingMap({ root: repositoryRoot });
	let committed;
	try {
		committed = await readFile(
			path.join(repositoryRoot, MAP_RELATIVE_PATH),
			"utf8",
		);
	} catch (error) {
		if (error?.code !== "ENOENT") throw error;
		return {
			ok: false,
			errors: [`map file is missing: ${MAP_RELATIVE_PATH}`],
			generated,
			committed: null,
		};
	}
	if (committed.replace(/\r\n?/g, "\n") === generated.text)
		return { ok: true, errors: [], generated, committed };
	const parsed = parseToolingMap(committed);
	const differences = diffToolingMaps(generated.files, parsed);
	if (differences.length === 0) differences.push("content differs");
	return {
		ok: false,
		errors: [`generated map differs: ${differences.join("; ")}`],
		generated,
		committed,
	};
}
